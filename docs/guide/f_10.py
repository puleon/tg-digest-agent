from figs import Fig, gbars


def injection_path() -> str:
    f = Fig(780, 300)
    f.text(20, 22, 'Косвенная инъекция: атакующий пишет пост, а не сообщение агенту', 12.5, 'bold', anchor='start')
    path = [('Атакующий', ['публикует пост', 'в канале'], 'warn'), ('Коллектор', ['сохраняет', 'как есть'], 'col'),
            ('Индекс', ['пост находится', 'по теме'], 'srch'), ('Контекст', ['пост попадает', 'в промпт'], 'srch'),
            ('Модель', ['читает и…', 'подчиняется?'], 'llm'), ('Ответ', ['пользователю'], 'svc')]
    for i, (t, ls, k) in enumerate(path):
        x = 20 + i * 127
        f.box(x, 45, 112, 64, t, ls, k, tsize=12, lsize=9.5)
        if i:
            f.line(x - 14, 77, x - 2, 77, 'ext', sw=1.4)
    defs = [(1, 'флаг injection_flag при обогащении', 147 + 56, '2'), (2, 'карантин: пост не дойдёт до модели', 400 + 10, '2'),
            (3, 'маркеры «это данные, не команды»', 527 + 30, '1'), (4, 'проверка ответа', 655 + 20, '4')]
    for i, (n, t, x, num) in enumerate(defs):
        y = 150 + (i % 2) * 52
        f.line(x, 112, x, y - 2, 'ing', sw=1.3)
        f.circle(x, y + 14, 12, 'ing', fill='#059669')
        f.text(x, y + 18.5, num, 11, 'bold', color='#ffffff')
        f.text(x + 18, y + 19, t, 10.5, kind='ing', anchor='start')
    f.rect(20, 256, 740, 34, 'ing', r=8, fill='#ecfdf5')
    f.text(32, 278, 'Защита 3 (нет записи из контента) — архитектурная: модель не выбирает инструменты вовсе.', 11,
           'bold', kind='ing', anchor='start')
    return f.render()


