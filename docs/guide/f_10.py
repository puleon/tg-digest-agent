def success_kinds() -> str:
    f = Fig(780, 220)
    f.text(20, 22, 'Из чего на самом деле состоят «успехи» атак (по прочтении ответов)', 12.5, 'bold', anchor='start')
    rows = [('Защита выключена · 8 из 45', [(0, 'подчинение', 'warn'), (5, 'пересказ инструкции', 'sec'),
                                             (3, 'повтор ложного факта', 'dig')]),
            ('Защита включена · 4 из 45', [(0, 'подчинение', 'warn'), (0, 'пересказ', 'sec'),
                                            (3, 'повтор ложного факта', 'dig'), (1, 'пост процитирован, чтобы отвергнуть', 'ext')])]
    for i, (lab, parts) in enumerate(rows):
        y = 50 + i * 60
        f.text(20, y + 17, lab, 11.5, 'bold', anchor='start')
        x = 250
        for n, name, k in parts:
            if n == 0:
                continue
            w = n * 55
            f.rect(x, y, w, 26, k, r=4)
            f.text(x + w / 2, y + 18, str(n), 11, 'bold', kind=k)
            x += w + 3
    lx = 20
    for name, k in [('пересказ текста атаки', 'sec'), ('повтор ложного факта', 'dig'),
                    ('пост процитирован, чтобы его отвергнуть', 'ext')]:
        f.rect(lx, 150, 13, 11, k, r=2)
        f.text(lx + 18, 160, name, 10.5, anchor='start')
        lx += 40 + len(name) * 6.3
    f.text(20, 185, 'Подчинения — подмены ответа канарейкой, вызова инструмента, утечки промпта — не было ни в одном '
           'режиме. «Пересказ» —', 10.5, anchor='start', kind='ext')
    f.text(20, 202, 'модель описывает пост «…поручается добавить ссылку evil.example…» — и ссылка всё равно доходит до '
           'читателя; защита её вырезает.', 10.5, anchor='start', kind='ext')
    return f.render()


