from figs import Fig, gbars


def profile_parts() -> str:
    f = Fig(780, 290)
    f.text(20, 22, 'Из 34 голосов — три представления вкуса', 12.5, 'bold', anchor='start')
    f.box(20, 100, 140, 90, 'Голоса', ['12 👍  22 👎', 'оценки постов', 'на онбординге'], 'you', tsize=12.5, lsize=10.5)
    parts = [('Веса тем', ['фантастика 0,47', 'кино 0,40', 'юмор 0,13'], 'сглаживание Лапласа', 40),
             ('Привязанность к каналам', ['@mirf_ru 0,57', '@starlighthousekeeping 0,48', 'незнакомый канал 0,35'],
              'байесовское среднее', 120),
             ('Центры интересов', ['2 центра (k-means)', 'по векторам лайков', 'BGE-M3'], 'кластеризация', 200)]
    for t, ls, how, y in parts:
        f.box(220, y, 280, 70, t, ls, 'dig', tsize=12, lsize=10)
        f.line(160, 145, 218, y + 35, 'dig', sw=1.3)
        f.text(512, y + 40, how, 10.5, kind='ext', anchor='start', italic=True)
    f.text(20, 282, 'Профиль хранится в user_profile и пересобирается по команде; голоса копятся в feedback.', 10.5,
           anchor='start', kind='ext')
    return f.render()


def score_bar() -> str:
    f = Fig(780, 200)
    f.text(20, 22, 'Оценка поста 17867 («Первый тизер „Соника в кино 4“») из выпуска владельца: 0,660', 12.5, 'bold',
           anchor='start')
    parts = [('похожесть', 0.45, 0.624, 'dig'), ('тема', 0.15, 0.700, 'srch'), ('канал', 0.15, 0.556, 'col'),
             ('популярность', 0.15, 0.607, 'svc'), ('новизна', 0.10, 1.0, 'ing')]
    x, sc = 20, 1000
    for name, w, v, k in parts:
        width = w * v * sc
        f.rect(x, 50, width, 40, k, r=3)
        f.text(x + width / 2, 75, f'{w * v:.3f}', 11, 'bold', kind=k)
        f.text(x + width / 2, 110, name, 10.5, kind=k)
        f.text(x + width / 2, 126, f'{w:.2f} × {v:.2f}', 9.5, kind='ext')
        x += width + 2
    f.text(20, 160, 'Сумма = 0,45·похожесть + 0,15·тема + 0,15·канал + 0,15·популярность + 0,10·новизна'
           ' − 0,5 за рекламу − 0,3 за качество < 2,5.', 10.5, anchor='start')
    f.text(20, 180, 'Из этих же слагаемых собирается ответ на «почему этот пост?» — без обращения к модели.', 10.5,
           anchor='start', kind='ext')
    return f.render()


def digest_crew() -> str:
    f = Fig(780, 270)
    f.text(20, 22, 'Редакция выпуска: двое из кода, двое из модели', 12.5, 'bold', anchor='start')
    f.box(20, 60, 150, 110, 'Планировщик', ['код', 'бюджет 10 мин →', '10 пунктов,', 'квоты тем 4/4/2'], 'dig',
          tsize=12.5, lsize=10)
    f.box(200, 60, 160, 110, 'Куратор', ['код, жадный выбор', '≤ 2 на канал', '60 % свежих', '1 на кластер, без',
                                         'повторов 10 выпусков'], 'dig', tsize=12.5, lsize=9.5)
    f.box(400, 60, 150, 110, 'Редактор', ['модель', 'заголовок ≤ 8 слов', '+ одна строка', '«почему»'], 'llm',
          tsize=12.5, lsize=10)
    f.box(600, 60, 160, 110, 'Критик', ['модель + код', 'выдумка? спойлер?', 'кликбейт?', 'все ли посты на месте?'],
          'llm', tsize=12.5, lsize=10)
    f.line(170, 115, 198, 115, 'dig', sw=1.6)
    f.line(360, 115, 398, 115, 'dig', sw=1.6)
    f.line(550, 100, 598, 100, 'llm', sw=1.6)
    f.path('M600,135 C580,165 570,165 552,135', 'warn', sw=1.6)
    f.label(575, 182, 'замечания, ≤ 2 раунда', kind='warn', size=10)
    f.text(20, 215, 'Кандидаты: посты за 7 дней по оценке интереса (или по просмотрам — бейзлайн). Правила состава '
           'проверяются точно,', 10.5, anchor='start', kind='ext')
    f.text(20, 232, 'поэтому они в коде; читать текст и замечать выдумку может только модель. Число раундов критика '
           'хранится у выпуска.', 10.5, anchor='start', kind='ext')
    f.text(20, 255, 'Выпуск владельца: критик дважды вернул заголовки «Дюны» и «Полдня» — в постах этого не было.', 10.5,
           anchor='start', kind='dig')
    return f.render()


