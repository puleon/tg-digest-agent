    return gbars('Ранжирует ли оценка ваши посты лучше просмотров? (leave-one-out, AUC)',
                 [('36 голосов', [0.701, 0.427, 0.5]), ('34 голоса\n(без одного канала)', [0.606, 0.466, 0.5])],
                 [('оценка интереса v1', 'dig'), ('по просмотрам', 'svc'), ('случайно', 'ext')], 1.0, fmt='{:.3f}',
                 height=270, width=640)
