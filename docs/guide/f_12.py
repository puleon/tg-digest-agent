    verdicts = [('Батиста сыграет Кратоса', 'подтверждено', 'ing'), ('Херст получил травму', 'подтверждено', 'ing'),
                ('…на вторые сутки', 'противоречит', 'warn'), ('пост от 9 июля', 'не подтверждено', 'sec')]
    for i, (c, v, k) in enumerate(verdicts):
        y = 45 + i * 30
        f.rect(430, y, 190, 24, 'file', r=4)
        f.text(440, y + 16, c, 10, anchor='start')
        f.rect(630, y, 130, 24, k, r=4)
        f.text(695, y + 16, v, 10, kind=k)
        f.line(400, 105, 428, y + 12, 'ext', sw=1)
