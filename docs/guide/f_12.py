def kappa() -> str:
    f = Fig(780, 230)
    f.text(20, 22, 'Каппа Коэна: согласие сверх случайного', 12.5, 'bold', anchor='start')
    m = [[23, 11, 1], [7, 16, 11], [0, 3, 28]]
    f.text(66, 54, 'судья:', 10.5, anchor='end', kind='llm')
    for c in range(3):
        f.text(98 + c * 62, 54, str(c), 10.5, 'bold', kind='llm')
    for r in range(3):
        f.text(60, 84 + r * 34, f'человек {r}', 10.5, anchor='end', kind='you')
        for c in range(3):
            v = m[r][c]
            k = 'ing' if r == c else ('sec' if abs(r - c) == 1 else 'warn')
            f.rect(70 + c * 62, 64 + r * 34, 56, 28, k, r=4)
            f.text(98 + c * 62, 83 + r * 34, str(v), 12, 'bold', kind=k)
    f.text(60, 190, 'зелёное — совпало (67 из 100), жёлтое — соседние', 10, anchor='start', kind='ext')
    f.text(60, 205, 'оценки, красное — 0 против 2 (1 случай)', 10, anchor='start', kind='ext')
    f.rect(330, 50, 430, 160, 'srch', r=10, fill='#eef2ff')
    for i, (a, b) in enumerate([('наблюдаемое согласие  p₀ = 0,67', ''),
                                ('случайное  pₑ = Σ доля человека × доля судьи = 0,33', ''),
                                ('κ = (p₀ − pₑ) / (1 − pₑ) = 0,51', ''),
                                ('взвешенная κ (соседние оценки — полуошибка) = 0,62', ''),
                                ('порог спецификации: κ > 0,6', '')]):
        f.text(345, 78 + i * 28, a, 11, 'bold' if i in (2, 3) else 'normal', kind='srch', anchor='start')
    return f.render()


