def faith_flow() -> str:
    f = Fig(780, 210)
    f.text(20, 22, 'Верность фактам: ответ → атомарные утверждения → проверка каждого по источнику', 12.5, 'bold',
           anchor='start')
    f.box(20, 50, 190, 110, 'Ответ агента', ['«Кратоса сыграет Дэйв', 'Батиста [post 5808].', 'Херст получил', 'травму…»'],
          'svc', tsize=12, lsize=10)
    f.box(240, 50, 160, 110, 'extract_claims', ['модель режет ответ', 'на утверждения', '(≤ 20, без мнений', 'и оговорок)'],
          'llm', tsize=11.5, lsize=10)
