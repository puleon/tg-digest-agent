from figs import Fig, gbars, hbars


def ranking_metrics() -> str:
    f = Fig(780, 270)
    f.text(20, 22, 'Игрушечный пример: выдача из пяти постов и оценки 0 / 1 / 2 (в пуле 4 подходящих)', 12.5,
           'bold', anchor='start')
    grades = [2, 0, 1, 2, 0]
    kinds = {2: 'ing', 1: 'sec', 0: 'ext'}
    for i, g in enumerate(grades):
        y = 45 + i * 34
        f.text(30, y + 18, f'{i + 1}.', 11, 'bold', anchor='start')
        f.rect(55, y, 200, 26, kinds[g], r=4)
        f.text(65, y + 17, f'пост, оценка {g}', 10.5, kind=kinds[g], anchor='start')
        gain = (2 ** g - 1)
        import math
        f.text(270, y + 17, f'{gain} / log₂({i + 2}) = {gain / math.log2(i + 2):.2f}', 10.5, anchor='start',
               mono=True, kind=kinds[g])
    f.rect(470, 40, 290, 200, 'srch', r=10, fill='#eef2ff')
    lines = [('recall@5 = 3 / 4 = 0,75', 'какую долю подходящих нашли'),
             ('MRR = 1 / 1 = 1,0', 'на каком месте первый подходящий'),
             ('DCG@5 = 3 + 0 + 0,5 + 1,29 = 4,79', ''),
             ('идеал: 2, 2, 1, 1 → 5,82', ''),
             ('nDCG@5 = 4,79 / 5,82 = 0,82', 'насколько порядок близок к идеальному')]
    y = 64
    for main, sub in lines:
        f.text(484, y, main, 11, 'bold', kind='srch', anchor='start')
        y += 16
        if sub:
            f.text(484, y, sub, 9.5, kind='ext', anchor='start', italic=True)
            y += 18
        else:
            y += 4
    f.text(20, 258, 'Оценка 2 приносит втрое больше, чем 1 (2² − 1 = 3), а знаменатель логарифма штрафует за низкое место.',
           10.5, anchor='start', kind='ext')
    return f.render()


