"""Chapter 7: deduplication."""
from figs import Fig, gbars


def dedup_cascade() -> str:
    f = Fig(780, 300)
    f.text(20, 22, 'Каскад: от дешёвых и точных признаков к дорогим и шумным (рёбра на корпусе после пересборки)',
           12, 'bold', anchor='start')
    stages = [('Тот же текст', 'sha1 нормализованного', 'текста ≥ 20 символов', '77'),
              ('Обрезанный репост', 'один текст — начало', 'другого (≥ 100 симв.)', '2'),
              ('Тот же файл', 'sha256 байтов', 'картинки', '317'),
              ('Похожая картинка', 'pHash, расстояние', 'Хэмминга ≤ 6', '488'),
              ('Пересылка', 'один источник', 'пересылки', '1')]
    for i, (t, a, b, n) in enumerate(stages):
        x = 20 + i * 152
        f.box(x, 45, 140, 96, t, [a, b], 'ing', tsize=12, lsize=9.5, title_top=70)
        f.circle(x + 120, 125, 13, 'ing', fill='#059669')
        f.text(x + 120, 129.5, n, 9.5 if len(n) < 3 else 8.5, 'bold', color='#ffffff')
        if i:
            f.line(x - 12, 93, x - 2, 93, 'ext', sw=1.4)
    f.rect(20, 165, 740, 56, 'warn', r=10, fill='#fef2f2')
    f.text(36, 187, 'Вето (запрет склейки): иллюстрация — 303 ребра, шаблон мема по OCR — 26, рубрика — 15;', 11,
           'bold', kind='warn', anchor='start')
    f.text(36, 207, 'ещё 19 склеек заблокировано через третий пост (cannot-link в union-find)', 11, kind='warn',
           anchor='start')
    f.text(20, 248, 'Итог: 728 кластеров, 1 613 постов в них, самый большой — 8 постов. Остальные ≈ 15,7 тыс. постов '
           'уникальны.', 11, anchor='start')
    f.text(20, 268, 'Шестая ступень спецификации — близкие эмбеддинги в окне 7 дней — подготовлена в коде, но не включена: '
           'дешёвые', 10.5, anchor='start', kind='ext')
    f.text(20, 285, 'ступени с вето дали полноту 1,0 на разметке, а единственный промах отложенной выборки ей не исправить.',
           10.5, anchor='start', kind='ext')
    return f.render()


def phash_steps() -> str:
    f = Fig(780, 250)
    f.text(20, 22, 'Перцептивный хэш (pHash): картинка → 64 бита, которые переживают пережатие', 12.5, 'bold',
           anchor='start')
    # 1 image
    f.rect(20, 50, 110, 110, 'file', r=6)
    f.text(75, 100, 'мем', 12, 'bold', kind='file')
    f.text(75, 118, '1280×960', 10, kind='file')
    f.line(130, 105, 156, 105, 'ext')
    # 2 gray 32x32
    for r in range(8):
        for c in range(8):
            g = 90 + ((r * 37 + c * 53) % 140)
            f.raw(f'<rect x="{160 + c * 13}" y="{53 + r * 13}" width="13" height="13" fill="rgb({g},{g},{g})"/>')
    f.text(212, 175, 'серая 32×32', 10.5, kind='ext')
    f.line(268, 105, 294, 105, 'ext')
    # 3 DCT
    for r in range(8):
        for c in range(8):
            v = max(0, 230 - (r + c) * 26)
            col = f'rgb({255 - v // 2},{255 - v // 3},255)'
            f.raw(f'<rect x="{298 + c * 13}" y="{53 + r * 13}" width="13" height="13" fill="{col}" stroke="#c7d2fe" '
                  f'stroke-width="0.5"/>')
    f.rect(298, 53, 52, 52, 'srch', r=0, fill='none', sw=2)
    f.text(350, 175, 'DCT: частоты', 10.5, kind='srch')
    f.text(350, 191, 'берём угол 8×8', 10.5, kind='srch')
    f.line(406, 105, 432, 105, 'ext')
    # 4 bits
    bits = '0110100010100110100111000110001010011111001110001001011100101001'
    for i in range(64):
        r, c = divmod(i, 8)
        b = bits[i] == '1'
        f.raw(f'<rect x="{436 + c * 13}" y="{53 + r * 13}" width="12" height="12" fill="{"#4f46e5" if b else "#ffffff"}" '
              f'stroke="#a5b4fc" stroke-width="0.6"/>')
    f.text(488, 175, 'больше медианы?', 10.5, kind='srch')
    f.text(488, 191, '→ 1, иначе 0', 10.5, kind='srch')
    f.line(544, 105, 570, 105, 'ext')
    f.box(574, 60, 186, 92, '0x68a69c629f389729', ['pHash поста 8648', '', 'сравнение: сколько', 'битов различается'],
          'srch', tsize=11, lsize=10)
    f.text(20, 222, 'Низкие частоты описывают общую композицию картинки и почти не меняются при пережатии JPEG, '
           'изменении размера', 10.5, anchor='start', kind='ext')
    f.text(20, 239, 'и лёгкой обрезке. Расстояние Хэмминга ≤ 6 из 64 — «та же картинка»; на расстояниях 7–12 в разметке '
           'не нашлось ни одного дубля.', 10.5, anchor='start', kind='ext')
    return f.render()


def union_find() -> str:
    f = Fig(780, 300)
    f.text(20, 22, 'Union-find с запретом: почему третий пост не склеивает две разные истории', 12.5, 'bold',
           anchor='start')
    nodes = {'A': (90, 130, 'Канал 1: статья о', 'фото NASA (900 симв.)'),
             'B': (390, 70, 'Канал 3: то же фото', 'без текста'),
             'C': (690, 130, 'Канал 2: своя статья', 'о том же фото')}
    for k, (x, y, l1, l2) in nodes.items():
        f.circle(x, y, 26, 'ing')
        f.text(x, y + 6, k, 16, 'bold', kind='ing')
        f.text(x, y + 46, l1, 10, kind='ext')
        f.text(x, y + 60, l2, 10, kind='ext')
    f.line(116, 122, 364, 78, 'ing', head=False, sw=2)
    f.label(240, 92, 'тот же файл', kind='ing', size=10)
    f.line(416, 78, 664, 122, 'ing', head=False, sw=2)
    f.label(540, 92, 'тот же файл', kind='ing', size=10)
    f.path('M110,155 C300,250 480,250 670,155', 'warn', dash=True, head=False, sw=2)
    f.text(390, 250, '✕ вето «иллюстрация»: разные статьи', 11, 'bold', kind='warn')
    f.text(390, 266, 'из разных каналов — запрет склейки A и C', 10.5, kind='warn')
    f.text(20, 292, 'Без запрета транзитивность (A~B, B~C ⇒ A~C) сделала бы из двух статей один «дубль». С запретом B '
           'остаётся с одной из них.', 10.5, anchor='start', kind='ext')
    return f.render()


